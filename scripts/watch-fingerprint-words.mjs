// Writes watch/Sources/CookrewCore/FingerprintWords.swift from src/shared/fingerprint-words.ts,
// so the watch speaks a key's words from the very list the Mac and the page do, with no copy
// made by hand. tests/watch-fingerprint-words.test.ts checks the two lists are one.
//
// Run: node scripts/watch-fingerprint-words.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const source = readFileSync(`${root}src/shared/fingerprint-words.ts`, 'utf8')
const words = [...source.slice(source.indexOf('FINGERPRINT_WORDS')).matchAll(/'([a-z]+)'/g)].map((match) => match[1])
if (words.length !== 2048) throw new Error(`expected 2048 words, found ${words.length}`)
const lines = []
for (let at = 0; at < words.length; at += 8) lines.push(`    ${words.slice(at, at + 8).map((word) => `"${word}"`).join(', ')},`)
writeFileSync(
  `${root}watch/Sources/CookrewCore/FingerprintWords.swift`,
  `// GENERATED by scripts/watch-fingerprint-words.mjs from src/shared/fingerprint-words.ts. Do not edit.
// The BIP-39 English list: 2048 words, 11 bits each (see the TypeScript file for why).

public enum FingerprintWords {
  public static let all: [String] = [
${lines.join('\n').replace(/,$/, '')}
  ]
}
`
)
