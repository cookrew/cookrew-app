// Turns QA's raw feature sequences into the site's step frames.
//   registry/assets/site/raw/sequences.json  [{feature, step, file, title, caption}]
//   registry/assets/site/raw/<file>.png       full-size captures
// → registry/assets/site/seq-<feature>-<step>.jpg (1400) and -800.jpg, and
//   registry/src/site-sequences.ts with the sizes the pages need up front.
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const raw = path.join(root, 'registry', 'assets', 'site', 'raw')
const out = path.join(root, 'registry', 'assets', 'site')
const listFile = path.join(raw, 'sequences.json')
if (!existsSync(listFile)) {
  console.error('no sequences.json yet')
  process.exit(0)
}
const list = JSON.parse(readFileSync(listFile, 'utf8'))
const sips = (args) => execFileSync('sips', args, { stdio: ['ignore', 'pipe', 'ignore'] }).toString()
const size = (file) => {
  const text = sips(['-g', 'pixelWidth', '-g', 'pixelHeight', file])
  return [Number(/pixelWidth: (\d+)/.exec(text)[1]), Number(/pixelHeight: (\d+)/.exec(text)[1])]
}
const groups = {}
for (const item of list) {
  const src = path.join(raw, item.file)
  if (!existsSync(src)) continue
  const stem = `seq-${item.feature}-${item.step}`
  const large = path.join(out, `${stem}.jpg`)
  const small = path.join(out, `${stem}-800.jpg`)
  sips(['-s', 'format', 'jpeg', '-s', 'formatOptions', '78', '-Z', '1400', src, '--out', large])
  sips(['-s', 'format', 'jpeg', '-s', 'formatOptions', '74', '-Z', '800', src, '--out', small])
  const [width, height] = size(large)
  ;(groups[item.feature] ??= []).push({ file: `${stem}.jpg`, title: item.title, caption: item.caption, width, height })
}
const body = Object.entries(groups)
  .map(([feature, steps]) => `  ${JSON.stringify(feature)}: ${JSON.stringify(steps, null, 2).replace(/\n/g, '\n  ')}`)
  .join(',\n')
writeFileSync(
  path.join(root, 'registry', 'src', 'site-sequences.ts'),
  `// GENERATED by scripts/site-sequences.mjs from registry/assets/site/raw/sequences.json — do not edit.
export interface Step {
  file: string
  title: string
  caption: string
  width: number
  height: number
}
export const SEQUENCES: Readonly<Record<string, readonly Step[]>> = {
${body}
}
`
)
console.log(`site-sequences.ts: ${Object.keys(groups).length} features, ${list.length} steps`)
