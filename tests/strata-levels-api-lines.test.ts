import { describe, expect, it } from 'vitest'
import { STRATA_LINE_MAX } from '../src/shared/strata'
import { hostOf, line, noteTitle, promptLine, replyLine, statusVerb, taskLine } from '../src/main/levels/lines'

// Every prompt below is an invented lookalike of a shape seen on the board —
// never a real one.

describe('the task line', () => {
  it('prefers the Sous title, then the brief, then the prompt', () => {
    const prompts = ['Tidy the fixture loader']
    expect(taskLine({ title: 'Tidying the loader', brief: 'Own the loader', prompts })).toBe('Tidying the loader')
    expect(taskLine({ title: null, brief: 'Own the loader', prompts })).toBe('Own the loader')
    expect(taskLine({ title: '  ', brief: '', prompts })).toBe('Tidy the fixture loader')
    expect(taskLine({ title: null, brief: null, prompts: [] })).toBeNull()
  })

  it('skips a task notification and takes the request under it', () => {
    const prompt = [
      '<task-notification>',
      '<task-id>b7x2</task-id>',
      '<output-file>/tmp/out.txt</output-file>',
      '</task-notification>',
      'Rename the widget helper and update its callers'
    ].join('\n')
    expect(promptLine(prompt)).toBe('Rename the widget helper and update its callers')
  })

  it('skips a truncated notification with no closing tag', () => {
    expect(promptLine('<task-notification>\n<task-id>q1</task-id>\nPort the cache to the new API')).toBe('Port the cache to the new API')
  })

  it('treats a continued-session summary as noise and falls back to an older prompt', () => {
    const continued =
      'This session is being continued from a previous conversation that ran out of context. The summary below covers the earlier portion.\n\nAnalysis:\n- the user asked for things'
    expect(promptLine(continued)).toBe('')
    expect(taskLine({ title: null, brief: null, prompts: [continued, 'Write the migration for the orders table'] })).toBe(
      'Write the migration for the orders table'
    )
  })

  it('treats the local-command caveat, slash commands and interrupts as noise', () => {
    expect(promptLine('Caveat: The messages below were generated by the user while running local commands. DO NOT respond.')).toBe('')
    expect(promptLine('/clear')).toBe('')
    expect(promptLine('/model opus')).toBe('')
    expect(promptLine('<command-name>/compact</command-name>\n<command-message>compact</command-message>')).toBe('')
    expect(promptLine('[Request interrupted by user for tool use]')).toBe('')
  })

  it('keeps a prompt that starts with a path', () => {
    expect(promptLine('/srv/app/config.yaml has a typo on line 4')).toBe('/srv/app/config.yaml has a typo on line 4')
  })

  it('takes the first line with words, without markdown lead', () => {
    expect(promptLine('```\n---\n## Fix the flaky upload test\nmore')).toBe('Fix the flaky upload test')
  })

  it('stops looking back after a bounded number of noisy prompts', () => {
    const noise = Array.from({ length: 40 }, () => '/clear')
    expect(taskLine({ title: null, brief: null, prompts: [...noise, 'Too far back'] })).toBeNull()
  })

  it('caps at STRATA_LINE_MAX code points with an ellipsis', () => {
    const long = 'é🍳'.repeat(100)
    const out = taskLine({ title: null, brief: null, prompts: [long] })!
    expect(Array.from(out)).toHaveLength(STRATA_LINE_MAX)
    expect(out.endsWith('…')).toBe(true)
  })
})

describe('scrubbing', () => {
  it('scrubs secret shapes before the cut, so a cut never leaves a credential head', () => {
    const key = `sk-${'a1B2'.repeat(12)}`
    const prompt = `${'x'.repeat(130)} use ${key} for the call`
    const out = taskLine({ title: null, brief: null, prompts: [prompt] })!
    expect(out).not.toContain('sk-a1B2')
    expect(out.length).toBeLessThanOrEqual(STRATA_LINE_MAX)
  })

  it('scrubs titles, briefs, replies and bearer tokens', () => {
    const token = 'Z'.repeat(40)
    expect(taskLine({ title: `Call with bearer ${token}`, brief: null, prompts: [] })).toBe('Call with bearer [redacted]')
    expect(replyLine(`Done. The key is ghp_${'q'.repeat(30)}`)).toBe('Done. The key is [redacted]')
  })
})

describe('the reply and status lines', () => {
  it('takes the first real line of a reply', () => {
    expect(replyLine('\n\n## Done — 14 tests added\n\nDetails follow')).toBe('Done — 14 tests added')
    expect(replyLine(null)).toBeNull()
    expect(replyLine('   ')).toBeNull()
  })

  it('keeps the status verb and drops the ticking counters', () => {
    expect(statusVerb('✻ Cerebrating… (34s · ↓ 2.1k tokens · esc to interrupt)')).toBe('Cerebrating…')
    expect(statusVerb(null)).toBeNull()
  })

  it('collapses whitespace in any line', () => {
    expect(line('  a \n\t b  ')).toBe('a b')
  })
})

describe('attachment titles', () => {
  it('names a note by its custom name, else its first real line', () => {
    expect(noteTitle({ customName: 'Plan', content: '# x', name: 'x' })).toBe('Plan')
    expect(noteTitle({ customName: null, content: '\n# Release checklist\n- one', name: 'release-checklist' })).toBe('Release checklist')
    expect(noteTitle({ customName: null, content: '', name: 'untitled' })).toBe('untitled')
  })

  it('keeps host and path of a browser, never the query or fragment', () => {
    expect(hostOf('https://github.com/acme/app/pull/482?token=abc#diff')).toBe('github.com/acme/app/pull/482')
    expect(hostOf('http://localhost:5280/')).toBe('localhost:5280')
    expect(hostOf('https://user:pw@example.dev/a')).toBe('example.dev/a')
    expect(hostOf('file:///Users/someone/reports/report.html')).toBe('file · report.html')
    expect(hostOf('about:blank')).toBe('about')
    expect(hostOf('')).toBeNull()
  })
})
