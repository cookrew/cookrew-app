    expect(STREAM_STATE_VERSION).toBe(2)
    const old = parseStreamState(JSON.stringify({ version: 1, cursor: { file: 'a.jsonl', byteOffset: 10, ordinal: 5 }, anomalies: {}, rolledBack: [], index: [] }))
