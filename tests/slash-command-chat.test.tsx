// SLASH COMMANDS ARE PART OF THE CONVERSATION (owner, 2026-11-24: "/compact,
// /goal … are not recorded in the chat"). Claude Code writes every command it
// runs into its session file; the parsers used to drop them all as noise, so a
// /model never showed, and the turn a /goal started was filed under the turn
// before it. A command that asks the model for a turn is now a checkpoint of
// its own; one that asks for nothing stands in the chat where it ran, with
// what it printed. Record shapes are the ones measured on 2.1.241-2.1.322.
import { describe, expect, it } from 'vitest'
import { renderToStaticMarkup } from 'react-dom/server'
import { isNoisePrompt, parseSessionTurns, slashCommandOf } from '../src/shared/session-turns'
import { parseClaudeTrace, parseClaudeTraceDocument, parseCodexTrace, type TraceBlock } from '../src/shared/trace-blocks'
import { traceBlockOf } from '../src/shared/stream-turns'
import { buildForkedSessionLinesAtTurn, buildForkedSessionLinesAtUuid, buildForkedSessionLinesForUuids } from '../src/shared/claude-fork'
import { parseStreamState, STREAM_STATE_VERSION } from '../src/main/stream-state'
import { chatLegsOf } from '../src/renderer/src/chat-fold'
import { TranscriptRow } from '../src/renderer/src/TranscriptRow'
import { TranscriptLookContext, type TranscriptLook } from '../src/renderer/src/transcript-look'

const T0 = Date.parse('2026-11-24T10:00:00.000Z')
const iso = (ms: number): string => new Date(ms).toISOString()

let seq = 0
function record(type: string, body: Record<string, unknown>, ms: number): string {
  seq += 1
  return JSON.stringify({ type, uuid: `r${seq}`, timestamp: iso(T0 + ms), ...body })
}
const said = (content: unknown, ms: number, extra: Record<string, unknown> = {}): string =>
  record('user', { message: { role: 'user', content }, ...extra }, ms)
const answered = (words: string, ms: number, stop: string | null = 'end_turn'): string =>
  record('assistant', { message: { role: 'assistant', content: [{ type: 'text', text: words }], stop_reason: stop } }, ms)
const localCommand = (content: string, ms: number): string =>
  record('system', { subtype: 'local_command', content, level: 'info', isMeta: false }, ms)

/** A local command as Claude writes it: name first, then message and args. */
const local = (name: string, args = ''): string =>
  `<command-name>/${name}</command-name>\n            <command-message>${name}</command-message>\n            <command-args>${args}</command-args>`
/** A prompt command (skill, custom command, workflow): message first. */
const prompted = (name: string, args = ''): string =>
  `<command-message>${name}</command-message>\n<command-name>/${name}</command-name>\n<command-args>${args}</command-args>`
const stdout = (text: string): string => `<local-command-stdout>${text}</local-command-stdout>`
const caveat = (ms: number): string =>
  said('<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>', ms, { isMeta: true })

/** A session: a prompt, a /model, a /goal that runs a turn, a /compact, a skill. */
function session(): string[] {
  return [
    said('fix the login bug', 0),
    answered('Fixed: the token was read before it was set.', 1000),
    caveat(2000),
    said(local('model', 'opus'), 2001),
    said(stdout('Set model to \u001b[1mOpus 5\u001b[22m and saved as your default'), 2002),
    said(local('goal', 'ship the release notes'), 3000),
    said(stdout('Goal set: ship the release notes'), 3001),
    said('A session-scoped Stop hook is now active with condition: "ship the release notes".', 3002, { isMeta: true }),
    answered('Working toward the goal: drafting the notes.', 4000),
    localCommand(local('compact'), 5000),
    localCommand(stdout('\u001b[2mCompacted (ctrl+o to see full summary)\u001b[22m'), 5001),
    said(prompted('code-review', 'src/auth.ts'), 6000),
    said([{ type: 'text', text: 'Review the file for bugs.' }], 6001, { isMeta: true }),
    answered('Two issues found.', 7000)
  ]
}

describe('which commands are a turn', () => {
  it('a prompt command asks the model for a turn; a local one, /goal included, is read as written', () => {
    expect(slashCommandOf(prompted('code-review', 'x'))).toEqual({ name: 'code-review', args: 'x', prompts: true })
    expect(slashCommandOf(local('goal', 'ship it'))).toEqual({ name: 'goal', args: 'ship it', prompts: false })
    expect(slashCommandOf(local('compact'))?.prompts).toBe(false)
    expect(slashCommandOf(local('model', 'opus'))?.prompts).toBe(false)
    expect(slashCommandOf('fix the <command-name> parser')).toBeNull()
    expect(slashCommandOf(stdout('ok'))).toBeNull()
  })

  it('a prompt command is not noise; local commands and their output still are', () => {
    expect(isNoisePrompt(prompted('code-review'))).toBe(false)
    expect(isNoisePrompt(local('goal', 'ship it'))).toBe(true)
    expect(isNoisePrompt(local('compact'))).toBe(true)
    expect(isNoisePrompt(stdout('Goal set: ship it'))).toBe(true)
  })
})

describe('the turns a session file holds', () => {
  const lines = session()
  const turns = parseSessionTurns(lines)

  it('a /goal and a skill open their own turn, read as typed; local commands open none', () => {
    expect(turns.map((t) => t.prompt)).toEqual(['fix the login bug', '/goal ship the release notes', '/code-review src/auth.ts'])
    expect(turns.map((t) => t.index)).toEqual([1, 2, 3])
  })

  it('the work a /goal started is its own reply, not the turn before it', () => {
    expect(turns[0].reply).toBe('Fixed: the token was read before it was set.')
    expect(turns[1].reply).toBe('Working toward the goal: drafting the notes.')
    expect(turns[2].reply).toBe('Two issues found.')
  })

  it('a session that opens on /goal is not blank', () => {
    const goalFirst = parseSessionTurns([said(local('goal', 'keep CI green'), 0), said(stdout('Goal set: keep CI green'), 1), answered('On it.', 1000)])
    expect(goalFirst.map((t) => [t.prompt, t.reply])).toEqual([['/goal keep CI green', 'On it.']])
  })

  // Claude 2.1.322 clears a goal on stop/off/reset/none/cancel too, and refuses
  // an over-long one: none of them prints "Goal set:", none runs a turn.
  for (const [args, printed] of [['stop', 'Goal cleared'], ['off', 'No goal set'], ['x'.repeat(5000), 'Goal is too long']]) {
    it(`/goal ${args.slice(0, 8)} that printed "${printed}" opens no turn, and stays a command line`, () => {
      const lines = [said('hi', 0), answered('hello', 1), said(local('goal', args), 2), said(stdout(printed), 3)]
      expect(parseSessionTurns(lines).map((t) => t.prompt)).toEqual(['hi'])
      const [block] = parseClaudeTrace(lines)
      expect(block.added?.map((a) => [a.text.slice(0, 13), a.output])).toEqual([[`/goal ${args}`.slice(0, 13), printed]])
    })
  }

  it('a /goal that set a goal is its turn\'s prompt, not also a line in the turn before', () => {
    const blocks = parseClaudeTrace(lines)
    expect(blocks[0].added?.map((a) => a.text)).toEqual(['/model opus'])
    expect(blocks[1].prompt).toBe('/goal ship the release notes')
  })

  it('a goal set in the newer system-record form opens its turn too', () => {
    const goal = parseSessionTurns([localCommand(local('goal', 'go'), 0), localCommand(stdout('Goal set: go'), 1), answered('going', 2)])
    expect(goal.map((t) => [t.prompt, t.reply])).toEqual([['/goal go', 'going']])
  })

  it('trace blocks and turns keep one numbering', () => {
    const blocks = parseClaudeTrace(lines)
    expect(blocks.map((b) => [b.index, b.id])).toEqual(turns.map((t) => [t.index, t.uuid]))
  })

  it('a fork after turn N counts the same turns', () => {
    const kept = buildForkedSessionLinesAtTurn(lines, { newSessionId: 'fork', keepPrompts: 1 })
    expect(parseSessionTurns(kept).map((t) => t.prompt)).toEqual(['fix the login bug'])
    expect(kept.some((line) => line.includes('Working toward the goal'))).toBe(false)
  })

  it('a fork counts a prompt command written as a block array, as the turns do', () => {
    const withArray = [said('first', 0), answered('one', 1), said([{ type: 'text', text: prompted('loop', '5m') }], 2), answered('looping', 3), said('third', 4), answered('three', 5)]
    const turns = parseSessionTurns(withArray)
    expect(turns.map((t) => t.prompt)).toEqual(['first', '/loop 5m', 'third'])
    expect(parseSessionTurns(buildForkedSessionLinesAtTurn(withArray, { newSessionId: 'f', keepPrompts: 2 })).map((t) => t.prompt)).toEqual(['first', '/loop 5m'])
    const atLoop = buildForkedSessionLinesAtUuid(withArray, { newSessionId: 'f', cutoffUuid: turns[1].uuid as string })
    expect(parseSessionTurns(atLoop).map((t) => t.prompt)).toEqual(['first', '/loop 5m'])
    const onlyLoop = buildForkedSessionLinesForUuids(withArray, { newSessionId: 'f', keepUuids: [turns[1].uuid as string] })
    expect(parseSessionTurns(onlyLoop).map((t) => [t.prompt, t.reply])).toEqual([['/loop 5m', 'looping']])
  })

  it('a fork cut at a /goal turn keeps the goal\'s own records out of the turn before', () => {
    const goalTurn = turns[1].uuid as string
    const before = buildForkedSessionLinesForUuids(lines, { newSessionId: 'f', keepUuids: [turns[0].uuid as string] })
    expect(before.some((line) => line.includes('Working toward the goal'))).toBe(false)
    const only = buildForkedSessionLinesForUuids(lines, { newSessionId: 'f', keepUuids: [goalTurn] })
    expect(parseSessionTurns(only).map((t) => t.reply)).toEqual(['Working toward the goal: drafting the notes.'])
  })
})

describe('local commands in the trace', () => {
  const blocks = parseClaudeTrace(session())
  const commands = (block: TraceBlock): Array<[string, string | undefined]> =>
    (block.added ?? []).filter((a) => a.command === true).map((a) => [a.text, a.output])

  it('stand in the turn they ran in, as typed, with what they printed in plain text', () => {
    expect(commands(blocks[0])).toEqual([['/model opus', 'Set model to Opus 5 and saved as your default']])
    // The newer `local_command` system record reads the same.
    expect(commands(blocks[1])).toEqual([['/compact', 'Compacted (ctrl+o to see full summary)']])
    expect(commands(blocks[2])).toEqual([])
  })

  it('stand where they ran: after the words the agent had said by then', () => {
    const [ran] = blocks[0].added ?? []
    expect(ran.at).toBe(blocks[0].reply.length)
    expect(blocks[1].added?.[0].at).toBe(blocks[1].reply.length)
  })

  it('a command that printed nothing has no output', () => {
    const [block] = parseClaudeTrace([said('hi', 0), answered('hello', 1), said(local('clear'), 2), localCommand(stdout(''), 3)])
    expect(block.added).toEqual([{ at: 5, calls: 0, thoughts: 0, text: '/clear', command: true }])
  })

  it('output that does not follow a command is not pinned to an earlier one', () => {
    const [block] = parseClaudeTrace([
      said('hi', 0),
      said(local('model', 'opus'), 1),
      answered('hello', 2),
      said(stdout('stray'), 3)
    ])
    expect(block.added?.[0].output).toBeUndefined()
  })

  it('commands before the first prompt lead that turn', () => {
    const [block] = parseClaudeTrace([
      caveat(0),
      said(local('model', 'opus'), 1),
      said(stdout('Set model to Opus 5'), 2),
      said('hello', 10),
      answered('hi', 11)
    ])
    expect(block.prompt).toBe('hello')
    expect(block.lead).toEqual([{ at: 0, calls: 0, thoughts: 0, text: '/model opus', command: true, output: 'Set model to Opus 5' }])
    expect(block.added).toBeUndefined()
  })

  it('compact markers still sit after the same turn', () => {
    const lines = [
      ...session().slice(0, 9),
      record('system', { subtype: 'compact_boundary', compactMetadata: { preTokens: 100, postTokens: 10 } }, 4500),
      ...session().slice(9)
    ]
    expect(parseClaudeTraceDocument(lines).markers).toEqual([{ kind: 'compact', afterIndex: 2, preTokens: 100, postTokens: 10 }])
  })

  it('the stream projection carries them through', () => {
    const [block] = parseClaudeTrace([said(local('model'), 0), said('hello', 1)])
    expect(traceBlockOf({ ...block, ordinal: 1 } as Parameters<typeof traceBlockOf>[0]).lead).toEqual(block.lead)
  })
})

describe('codex /goal', () => {
  const meta = JSON.stringify({ timestamp: iso(T0), type: 'session_meta', payload: { session_id: 'th', timestamp: iso(T0), cwd: '/w' } })
  const prompt = (text: string, ms: number): string =>
    JSON.stringify({ timestamp: iso(T0 + ms), type: 'event_msg', payload: { type: 'user_message', message: text } })
  const reply = (text: string, ms: number): string =>
    JSON.stringify({ timestamp: iso(T0 + ms), type: 'event_msg', payload: { type: 'agent_message', message: text } })
  const done = (ms: number): string => JSON.stringify({ timestamp: iso(T0 + ms), type: 'event_msg', payload: { type: 'task_complete' } })
  const internal = (source: string, body: string, ms: number): string =>
    JSON.stringify({
      timestamp: iso(T0 + ms),
      type: 'response_item',
      payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text: `<codex_internal_context source="${source}">\n${body}\n</codex_internal_context>` }] }
    })
  const rollout = (): string[] => [
    meta,
    prompt('fix the bug', 0),
    reply('fixed', 1000),
    done(1001),
    internal('user_goal', 'User set the goal: "ship the release notes"\nUser set goal status: "active".', 2000),
    reply('drafting the notes', 3000),
    done(3001),
    internal('user_goal', 'User set goal status: "paused".', 4000),
    prompt('and the changelog', 5000),
    reply('done', 6000)
  ]

  it('opens a turn of its own, read as typed', () => {
    const blocks = parseCodexTrace(rollout())
    expect(blocks.map((b) => [b.index, b.prompt, b.reply])).toEqual([
      [1, 'fix the bug', 'fixed'],
      [2, '/goal ship the release notes', 'drafting the notes'],
      [3, 'and the changelog', 'done']
    ])
    expect(blocks[1].final).toBe(true)
  })

  it('leaves the identity of every typed prompt where it was', () => {
    expect(parseCodexTrace(rollout()).map((b) => b.id)).toEqual(['th:p1', 'th:g2', 'th:p2'])
  })
})

describe('the row', () => {
  const blocks = parseClaudeTrace(session())
  const render = (block: TraceBlock, look: TranscriptLook): string =>
    renderToStaticMarkup(
      <TranscriptLookContext.Provider value={look}>
        <TranscriptRow id={block.index} block={block} active={false} placeholderHeight={undefined} titleMode="precise" translated={null} />
      </TranscriptLookContext.Provider>
    )

  it('splits the turn at the command, which is a command line, not a prompt bubble', () => {
    const legs = chatLegsOf(blocks[0])
    expect(legs.map((l) => [l.words, l.command])).toEqual([
      [null, undefined],
      ['/model opus', { output: 'Set model to Opus 5 and saved as your default' }]
    ])
  })

  for (const look of ['chat', 'log'] as const) {
    it(`draws the command and its output in the ${look}, after the reply it followed`, () => {
      const html = render(blocks[0], look)
      expect(html).toContain('<span class="ctx-command-line">/model opus</span>')
      expect(html).toContain('<span class="ctx-command-output">Set model to Opus 5 and saved as your default</span>')
      expect(html.match(/class="ctx-block-prompt"/g)).toHaveLength(1)
      expect(html.indexOf('Fixed: the token')).toBeLessThan(html.indexOf('ctx-command-line'))
    })

    it(`draws a /goal turn's prompt as typed in the ${look}`, () => {
      const html = render(blocks[1], look)
      expect(html).toContain('<div class="ctx-block-prompt">/goal ship the release notes</div>')
      expect(html).toContain('Working toward the goal')
    })
  }

  it('a translation stays on the closing answer, not under a command run after it', () => {
    const html = renderToStaticMarkup(
      <TranscriptRow id={1} block={blocks[0]} active={false} placeholderHeight={undefined} titleMode="precise" translated={{ index: 1, prompt: null, reply: 'TRANSLATED' }} />
    )
    expect(html).toContain('TRANSLATED')
    expect(html).not.toContain('Fixed: the token')
    expect(html.indexOf('TRANSLATED')).toBeLessThan(html.indexOf('ctx-command-line'))
  })

  it('draws commands that led a turn above its prompt', () => {
    const [block] = parseClaudeTrace([said(local('model', 'opus'), 0), said('hello', 1)])
    const html = render(block, 'chat')
    expect(html.indexOf('ctx-command-line')).toBeGreaterThan(-1)
    expect(html.indexOf('ctx-command-line')).toBeLessThan(html.indexOf('class="ctx-block-prompt"'))
  })
})

