import { writeFileSync } from 'node:fs'
import path from 'node:path'

/**
 * THE `cookrew` SHIM, ON THE APP'S OWN NODE.
 *
 * It was `exec node "<script>"`, which asks the machine for a Node it may not
 * have: round 1 on the Solis Linux box, Electron on Xvfb and no system Node,
 * answered `exec: node: not found`. The app already ships one. Electron is a
 * Node when ELECTRON_RUN_AS_NODE is set, in a dev checkout and in a packaged
 * build alike, and `process.execPath` is that binary in both.
 *
 * THE VARIABLE IS NOT OPTIONAL ANYWHERE THE BINARY IS RUN. Without it the
 * same binary is the app, and a second instance of the app closes the fleet's
 * panes. It also relies on the RunAsNode fuse staying on, which is why
 * electron-builder.yml is pinned by tests/cli-shim.test.ts.
 *
 * The CLI drops the variable again as it starts (cli/cookrew.mjs), so a
 * command run by `cookrew secret exec` does not inherit it.
 *
 * A system node stays as the fallback for one case: the binary this was
 * written for has moved (an update, an AppImage that unmounted).
 */

const quoted = (value: string): string => `'${value.replace(/'/g, `'\\''`)}'`

/** The wrapper a pane finds on PATH. */
export function cliWrapper(script: string, runtime: string): string {
  return [
    '#!/bin/sh',
    '# Generated by Cookrew at launch (src/main/cli-shim.ts).',
    `RUNTIME=${quoted(runtime)}`,
    `SCRIPT=${quoted(script)}`,
    'export ELECTRON_RUN_AS_NODE=1',
    'if [ -x "$RUNTIME" ]; then exec "$RUNTIME" "$SCRIPT" "$@"; fi',
    'if command -v node >/dev/null 2>&1; then exec node "$SCRIPT" "$@"; fi',
    'echo "cookrew: the app binary has moved and there is no node here. Open Cookrew once, then try again." >&2',
    'exit 127',
    ''
  ].join('\n')
}

/**
 * Where the binary is, for the launcher `npm run install-cli` puts on the
 * system PATH: that one is written once and outlives every app update, so it
 * reads this at run time rather than baking a path.
 */
export function publishCliRuntime(home: string, runtime: string): void {
  writeFileSync(path.join(home, 'runtime'), runtime)
}
