import type { StoredPathReport } from '../shared/path-report'

const PLANES = new Set(['LAN', 'TAILNET', 'RELAY'])
const KINDS = new Set(['socket', 'image', 'opaque', 'rtc'])
const OUTCOMES = new Set(['answered', 'timeout', 'closed', 'unbound'])
const PERMISSIONS = new Set(['granted', 'denied', 'prompt', 'unsupported'])
const CONTEXTS = new Set(['standalone', 'browser'])
const DURATION_BUCKETS = [0, 50, 100, 250, 500, 1_000, 2_000, 5_000, 10_000, 30_000, 60_000, 120_000] as const

/** Fixed upper-bound buckets retain useful short timings without reproducing arbitrary numbers. */
const durationBucket = (ms: number | null): number | 'over-120s' | null => {
  if (typeof ms !== 'number' || !Number.isFinite(ms) || ms < 0) return null
  return DURATION_BUCKETS.find((bound) => ms <= bound) ?? 'over-120s'
}

/** A bounded projection: never copy untrusted report text into a local diagnostic summary. */
export function summarizePathReports(reports: readonly StoredPathReport[]) {
  return reports.map((report) => ({
    // The receipt time is generated by this Mac's report store, not the sender.
    receivedAt: report.receivedAt,
    plane: PLANES.has(report.plane) ? report.plane : 'unknown',
    permission: PERMISSIONS.has(report.permission) ? report.permission : 'unknown',
    context: report.context && CONTEXTS.has(report.context) ? report.context : 'unknown',
    attempts: report.attempts.length,
    probes: (report.probes ?? []).map((probe) => ({
      kind: KINDS.has(probe.kind) ? probe.kind : 'unknown',
      outcome: OUTCOMES.has(probe.outcome) ? probe.outcome : 'unknown',
      ms: durationBucket(probe.ms)
    }))
  }))
}
