// THE LINES A LEVEL SHOWS: an agent's task, its reply, its status verb, a
// note's title. Pure: no fs, no store, no clock. Every line that leaves the
// desktop for the fleet API passes through `line()` — scrubbed FIRST and cut
// SECOND, so a cut can never break a credential's shape and leak its head.
//
// The task line is the Sous title, else the card's brief, else the first REAL
// line of the current or last prompt. "Real" excludes harness noise: wrapper
// tags (board.ts · stripSystemWrappers), a continued-session summary, the
// local-command caveat, a bare slash command, an interrupt marker.

import { FLEET_LINE_MAX } from '../../shared/fleet'
import { stripSystemWrappers } from '../../shared/board'
import { scrubShapes, type Scrub } from '../scrub'

/**
 * A prompt whose first real line opens with one of these is machine-written
 * from end to end — the whole prompt is skipped, not just that line: the rest
 * of a continued-session summary is "Analysis:" and bullet points, never the
 * task the owner typed.
 */
const NOISE_PROMPT_OPENERS: readonly RegExp[] = [
  /^this session is being continued from a previous conversation/i,
  /^caveat: the messages below were generated by the user while running local commands/i,
  /^\[request interrupted by user/i,
  /^base directory for this skill:/i,
  // A slash command and its arguments: `/clear`, `/model opus`. A path is not
  // one — `/Users/x is broken` has a second slash in its first word.
  /^\/[a-z][a-z0-9:_-]*(?:\s|$)/i
]

/** Lines that carry no words: fences, rules, bare punctuation. */
const WORDLESS = /^[^\p{L}\p{N}]*$/u

/** Leading markdown a one-line label does not want: headings, quotes, bullets. */
const MARKDOWN_LEAD = /^(?:#{1,6}\s+|>\s*|[-*+]\s+)+/

/** Collapse whitespace, scrub, then cut to `max` code points with an ellipsis. */
export function line(text: string | null | undefined, scrub: Scrub = scrubShapes, max = FLEET_LINE_MAX): string | null {
  if (typeof text !== 'string') return null
  const collapsed = scrub(text.replace(/\s+/g, ' ').trim())
  if (collapsed.length === 0) return null
  const points = Array.from(collapsed)
  return points.length <= max ? collapsed : `${points.slice(0, max - 1).join('').trimEnd()}…`
}

/** The first line of `text` that has words in it, markdown lead removed; '' when none. */
export function firstRealLine(text: string): string {
  for (const raw of text.split('\n')) {
    const trimmed = raw.replace(MARKDOWN_LEAD, '').trim()
    if (trimmed.length > 0 && !WORDLESS.test(trimmed)) return trimmed
  }
  return ''
}

/** The prompt's first real line, or '' when the prompt is harness noise. */
export function promptLine(prompt: string | null | undefined): string {
  if (typeof prompt !== 'string' || prompt.length === 0) return ''
  const first = firstRealLine(stripSystemWrappers(prompt))
  if (first.length === 0) return ''
  return NOISE_PROMPT_OPENERS.some((opener) => opener.test(first)) ? '' : first
}

export interface TaskLineInput {
  /** Sous title of the current (or last displayed) turn. */
  title: string | null | undefined
  /** The sentence the card was recruited for. */
  brief: string | null | undefined
  /** Newest first: the in-flight prompt (if any), then the ledger's prompts. */
  prompts: Iterable<string | null | undefined>
}

/** How far back a task line looks for a prompt that is not noise. */
export const TASK_LOOKBACK = 24

/** Sous title, else brief, else the first real line of the newest real prompt. Scrubbed, capped. */
export function taskLine(input: TaskLineInput, scrub: Scrub = scrubShapes): string | null {
  const title = line(input.title, scrub)
  if (title) return title
  const brief = line(input.brief, scrub)
  if (brief) return brief
  let looked = 0
  for (const prompt of input.prompts) {
    if (looked >= TASK_LOOKBACK) break
    looked += 1
    const found = promptLine(prompt)
    if (found) return line(found, scrub)
  }
  return null
}

/** First real line of a reply (or a streaming message). Scrubbed, capped. */
export function replyLine(text: string | null | undefined, scrub: Scrub = scrubShapes): string | null {
  if (typeof text !== 'string') return null
  return line(firstRealLine(stripSystemWrappers(text)), scrub)
}

/**
 * The live status VERB: 'Cerebrating… (34s · ↓ 2.1k tokens)' → 'Cerebrating…'.
 * The counters tick every second; the shell draws elapsed time from
 * phaseSince, so the wire changes when the verb does, not once a second.
 */
export function statusVerb(status: string | null | undefined, scrub: Scrub = scrubShapes): string | null {
  if (typeof status !== 'string') return null
  const verb = status.replace(/\s*\(.*$/, '').replace(/^[^\p{L}\p{N}]+/u, '')
  return line(verb, scrub, 48)
}

/** A note's title: its custom name, else its first real line. */
export function noteTitle(note: { customName: string | null; content: string; name: string }, scrub: Scrub = scrubShapes): string {
  return line(note.customName, scrub) ?? line(firstRealLine(note.content), scrub) ?? note.name
}

/** Host + path of a URL, never its query or fragment. Non-web URLs keep scheme-less identity. */
export function hostOf(url: string | null | undefined): string | null {
  if (typeof url !== 'string' || url.length === 0) return null
  try {
    const parsed = new URL(url)
    if (parsed.protocol === 'file:') {
      const leaf = parsed.pathname.split('/').filter(Boolean).pop()
      return leaf ? `file · ${decodeURIComponent(leaf)}` : 'file'
    }
    if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') return parsed.protocol.replace(/:$/, '')
    const pathPart = parsed.pathname === '/' ? '' : parsed.pathname.replace(/\/$/, '')
    return line(`${parsed.host}${pathPart}`, scrubShapes, FLEET_LINE_MAX)
  } catch {
    return null
  }
}
