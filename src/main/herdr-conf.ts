// The herdr config Cookrew starts its own server with (HERDR_CONFIG_PATH).
// PtyManager writes it to the runtime dir at every app start, and the server
// reads it when it starts, so a server Cookrew spawns always runs on it.

/**
 * Cookrew's herdr config — and it is not cosmetic.
 *
 * herdr's chrome (sidebar, tab bar, pane borders, scrollbars) is what made an
 * earlier attach measure 97KB of TUI and get written off as unhostable. With
 * the chrome off, `agent attach` streams the pane and nothing else: measured at
 * 27ms echo, 0 bytes over 3s idle, no chrome words in the stream.
 *
 * `host_cursor = "native"` matters too — Cookrew renders into xterm.js, which
 * draws its own cursor from the escape stream, so herdr must not paint a
 * second one as cell content.
 */
export const HERDR_CONF = [
  '# Generated by Cookrew. Chrome is off so `agent attach` is a transparent',
  '# pane stream rather than a terminal UI.',
  'onboarding = false',
  '',
  '[ui]',
  'sidebar_start_collapsed = true',
  'sidebar_collapsed_mode = "hidden"',
  'hide_tab_bar_when_single_tab = true',
  'pane_borders = false',
  'pane_scrollbars = false',
  'pane_gaps = false',
  'host_cursor = "native"',
  'confirm_close = false',
  'prompt_new_tab_name = false',
  'prompt_new_workspace_name = false',
  '',
  // The cookrew herdr server died four times on 2026-08-08/09, killing every
  // agent each time; one death followed an update check within minutes and
  // none logged a stop request. The background updater is the one lifecycle
  // actor Cookrew can switch off, so it is off — Cookrew's agents must never
  // be collateral of a version check.
  '[update]',
  'version_check = false',
  'manifest_check = false',
  '',
  // herdr 0.9 resumes the agent it recorded for each restored pane by itself:
  // about a second after a server restart it runs `claude --resume <id>` (or
  // `codex resume <id>`) as a child of the restored login shell. That agent
  // has the SERVER's env and herdr's command line, not Cookrew's boot: no
  // COOKREW_TERMINAL_ID, socket, cookrew shim, route or Magpie --mcp-config
  // (2026-11-09: nine fleet panes, Roaster among them, `cookrew secret exec`
  // refused and its MCP gone). With this off the pane comes back a bare
  // shell, a husk, and Cookrew's boot script resumes the same session the
  // first time anything reaches the card (HerdrHostMultiplexer.ensureSession).
  // A herdr without the key ignores it ("unknown config key ... ignoring").
  //
  // Not herdr 0.9.2's self-reported resume command (`report-agent-session
  // <pane> -- <argv>`) instead: herdr types that argv into the restored shell,
  // so the agent is still a child of -zsh (panePid, codex pid binding), it only
  // exists from 0.9.2, and the argv would have to be re-reported on every
  // session rotation (/clear, a held-session fork, a codex rollout bound after
  // boot) or herdr resumes a stale session. Cookrew's spawn resolves the live
  // session at the moment it boots.
  '[session]',
  'resume_agents_on_restore = false'
].join('\n')
